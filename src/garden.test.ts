import { expect, test } from 'vitest'
import { earnRewards, parseGameProgress } from './game'
import { harvestCrop, parseGarden, plantCrop, upgradeBase } from './garden'
const initial = (coins = 0) => ({ ...parseGameProgress(null), coins })
test('migrates old saves without changing balances and repairs invalid garden data', () => {
  const old = parseGameProgress(JSON.stringify({ xp: 120, coins: 45, unlocked: ['recommend'], records: { best: 100 } }))
  expect(old.coins).toBe(45)
  expect(old.xp).toBe(120)
  expect(old.unlocked).toEqual(['recommend'])
  expect(old.garden).toEqual(parseGarden(null))
  expect(parseGarden({ baseLevel: 99, plots: [{ crop: 'fake', readyAt: 1 }] })).toEqual(parseGarden(null))
  expect(parseGarden({ baseLevel: 1, plots: [null, null, { crop: 'peach', readyAt: 1 }] }).plots[2]).toBeNull()
})
test('planting spends exactly once and rejects occupied, locked, invalid and unaffordable plots', () => {
  const start = initial(10)
  const planted = plantCrop(start, 0, 'strawberry', 1000)
  expect(planted.coins).toBe(7)
  expect(planted.garden.plots[0]).toEqual({ crop: 'strawberry', readyAt: 61000 })
  expect(plantCrop(planted, 0, 'strawberry', 1000)).toBe(planted)
  expect(plantCrop(start, 2, 'strawberry', 1000)).toBe(start)
  expect(plantCrop(start, -1, 'strawberry', 1000)).toBe(start)
  expect(plantCrop(start, 1, 'orange', 1000)).toBe(start)
  const broke = initial()
  expect(plantCrop(broke, 0, 'strawberry', 1000)).toBe(broke)
})
test('offline growth survives saving and harvest cannot be claimed early or twice', () => {
  const planted = plantCrop(initial(3), 0, 'strawberry', 1000)
  expect(harvestCrop(planted, 0, 60999)).toBe(planted)
  const restored = parseGameProgress(JSON.stringify(planted))
  const harvested = harvestCrop(restored, 0, 999999)
  expect(harvested.coins).toBe(8)
  expect(harvested.garden.plots[0]).toBeNull()
  expect(harvestCrop(harvested, 0, 999999)).toBe(harvested)
})
test('base upgrades spend gold, preserve crops, unlock plots and increase learning and harvest rewards', () => {
  const planted = plantCrop(initial(400), 0, 'strawberry', 1000)
  const upgraded = upgradeBase(planted)
  expect(upgraded.coins).toBe(357)
  expect(upgraded.garden.baseLevel).toBe(2)
  expect(upgraded.garden.plots[0]).toEqual(planted.garden.plots[0])
  expect(plantCrop(upgraded, 2, 'orange', 1000).garden.plots[2]?.crop).toBe('orange')
  expect(harvestCrop(upgraded, 0, 61000).coins).toBe(367)
  const rewarded = earnRewards(upgraded, 'ramen', 2, 200, 'best')
  expect(rewarded.coins).toBe(8)
  expect(rewarded.progress.garden).toEqual(upgraded.garden)
  const maxed = upgradeBase(upgradeBase(upgraded))
  expect(maxed.garden.baseLevel).toBe(4)
  expect(upgradeBase(maxed)).toBe(maxed)
  const broke = initial(39)
  expect(upgradeBase(broke)).toBe(broke)
})
